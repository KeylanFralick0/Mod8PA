import math


# constants representing the species and count
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151


# instructor-provided function
# copy and paste into your solution
def read_penguin_row(row_number):
    penguin_row = ""

    # open the CSV file and skip the header row
    with open("PalmerPenguins.csv", "r") as penguin_file:
        penguin_file.readline()

        current_row = 1

        # search for the requested data row
        for row in penguin_file:
            if current_row == row_number:
                penguin_row = row.strip()
                break

            current_row += 1

    # return the requested row as a string
    return penguin_row


# calculate the percentage of penguins in a species group
def calculate_percentage(species_count, total_penguins):
    return species_count / total_penguins * 100


# classify a species group based on its percentage
def classify_species(species_percent):
    if species_percent < 25:
        return "small"
    elif species_percent < 40:
        return "medium"
    else:
        return "large"


# determine the position of a species group
def get_position_description(
        selected_species, largest_species, smallest_species):
    if selected_species == largest_species:
        return "largest"
    elif selected_species == smallest_species:
        return "smallest"
    else:
        return "middle-sized"


# display statistics for one species
def display_species_statistics(
        species, count, percentage, size_category,
        position_description, average_penguins):

    if count > average_penguins:
        average_position = "above"
    else:
        average_position = "below"

    print(f"{species} has {count} observations, "
          f"representing {percentage:.2f}% of the dataset.")
    print(f"{species} is classified as a "
          f"{size_category} species group.")
    print(f"{species} is the {position_description} "
          f"species group.")
    print(f"Its observation count is {average_position} the dataset "
          f"average of {average_penguins:.1f}.")


# display an individual penguin observation
def display_penguin_observation(
        sample_number, species, bill_length, bill_depth,
        body_mass, sex):

    print("Sample Penguin Observation")
    print(f"{'Sample Number:':<20}{sample_number}")
    print(f"{'Species:':<20}{species}")
    print(f"{'Bill length:':<20}{bill_length} mm")
    print(f"{'Bill depth:':<20}{bill_depth} mm")
    print(f"{'Body mass:':<20}{body_mass} g")
    print(f"{'Sex:':<20}{sex}")
    print()


# main program
def main():

    # create parallel lists containing species data
    species_names = [
        SP_CHINSTRAP,
        SP_GENTOO,
        SP_ADELIE
    ]

    species_counts = [
        NUM_CHINSTRAP,
        NUM_GENTOO,
        NUM_ADELIE
    ]

    # calculate dataset statistics
    total_species = len(species_names)
    total_penguins = sum(species_counts)
    average_penguins = total_penguins / total_species

    species_percentages = []

    for count in species_counts:
        percentage = calculate_percentage(count, total_penguins)
        species_percentages.append(percentage)

    average_penguins_rounded_up = math.ceil(average_penguins)

    # determine largest and smallest species groups
    largest_count = max(species_counts)
    smallest_count = min(species_counts)

    largest_index = species_counts.index(largest_count)
    smallest_index = species_counts.index(smallest_count)

    largest_species = species_names[largest_index]
    smallest_species = species_names[smallest_index]

    # display dataset statistics
    print("Introducing the Palmer Penguins:")
    print("\t" + SP_CHINSTRAP + "!")
    print("\t" + SP_GENTOO + "!")
    print("and last but not least...")
    print("\t" + SP_ADELIE + "!")
    print(f"There are a total of {total_species} "
          f"penguin species in this dataset.")
    print(f"There are a total of {total_penguins} "
          f"penguins in the dataset.")
    print(f"The average number of penguins per species is "
          f"{average_penguins:.1f}.")
    print("The average rounded up is",
          average_penguins_rounded_up, "penguins.")
    print()

    # display species statistics using a loop
    for index, species in enumerate(species_names):
        print(f"{species}: {species_counts[index]}"
              f" ({species_percentages[index]:.2f}%)")

    print()

    print(f"The species with the most observations is "
          f"{largest_species} with {largest_count} penguins.")
    print(f"The species with the fewest observations is "
          f"{smallest_species} with {smallest_count} penguins.")
    print()

    # retrieve the first penguin observation
    penguin_row = read_penguin_row(1)

    if penguin_row:
        print("Sample dataset row:")
        print(penguin_row)

        # split the CSV row into individual values
        penguin_data = penguin_row.split(",")

        # convert and extract values
        sample_number = int(penguin_data[0])
        species = penguin_data[1]
        bill_length = float(penguin_data[2])
        bill_depth = float(penguin_data[3])
        body_mass = int(float(penguin_data[5]))
        sex = penguin_data[6].strip()

        # display the first penguin observation
        display_penguin_observation(
            sample_number,
            species,
            bill_length,
            bill_depth,
            body_mass,
            sex
        )

    # retrieve a second penguin observation
    penguin_row = read_penguin_row(51)

    if penguin_row:
        print("Sample dataset row:")
        print(penguin_row)

        # split the CSV row into individual values
        penguin_data = penguin_row.split(",")

        # convert and extract values
        sample_number = int(penguin_data[0])
        species = penguin_data[1]
        bill_length = float(penguin_data[2])
        bill_depth = float(penguin_data[3])
        body_mass = int(float(penguin_data[5]))
        sex = penguin_data[6].strip()

        # display the second penguin observation
        display_penguin_observation(
            sample_number,
            species,
            bill_length,
            bill_depth,
            body_mass,
            sex
        )

    # create a list of sample row numbers
    sample_rows = [1, 2, 3, 4, 5]

    # create an empty list to store body masses
    body_masses = []

    # collect body masses from the CSV data
    for row_number in sample_rows:
        penguin_row = read_penguin_row(row_number)

        if penguin_row:
            penguin_data = penguin_row.split(",")

            # convert the body mass to an integer
            body_mass = int(float(penguin_data[5]))

            # append the body mass to the list
            body_masses.append(body_mass)

    # display the sample body masses
    print("\nSample Body Masses")
    print(body_masses)

    # calculate body mass summary statistics
    observations = len(body_masses)
    total_body_mass = sum(body_masses)
    smallest_body_mass = min(body_masses)
    largest_body_mass = max(body_masses)
    average_body_mass = total_body_mass / observations

    # display the body mass summary
    print("\nBody Mass Summary")
    print(f"Observations:       {observations}")
    print(f"Total body mass:    {total_body_mass} g")
    print(f"Smallest body mass: {smallest_body_mass} g")
    print(f"Largest body mass:  {largest_body_mass} g")
    print(f"Average body mass:  {average_body_mass:.2f} g")

    # associate species names with observation counts
    species_dictionary = {
        SP_CHINSTRAP: NUM_CHINSTRAP,
        SP_GENTOO: NUM_GENTOO,
        SP_ADELIE: NUM_ADELIE
    }

    # display species counts using the dictionary
    print("\nSpecies Counts Using a Dictionary")

    for species in species_dictionary:
        count = species_dictionary[species]
        print(f"{species}: {count}")

    # initialize the valid selection counter
    valid_selections = 0

    # repeatedly prompt the user to explore species
    print("Explore a species:")
    species_choice = input(
        "Enter Chinstrap, Gentoo, Adelie, or Done: "
    )

    while species_choice != "Done":

        # validate the species selection
        if species_choice not in species_names:
            print(
                f"{species_choice} is not one of the species "
                f"in this dataset."
            )

        else:
            # update the number of valid selections
            valid_selections += 1

            # determine the selected species
            selected_index = species_names.index(species_choice)

            selected_species = species_names[selected_index]
            selected_count = species_counts[selected_index]
            selected_percent = species_percentages[selected_index]

            # classify the selected species
            size_category = classify_species(selected_percent)

            # determine the species position
            position_description = get_position_description(
                selected_species,
                largest_species,
                smallest_species
            )

            # display selected species statistics
            display_species_statistics(
                selected_species,
                selected_count,
                selected_percent,
                size_category,
                position_description,
                average_penguins
            )

        # prompt for another species
        species_choice = input(
            "Enter Chinstrap, Gentoo, Adelie, or Done: "
        )

    # display the exploration summary
    print(f"You explored {valid_selections} valid species.")
    print("Exploration complete.")


# run the main program
main()